#[test]
fn executable_replaced_after_preparation_is_refused_at_spawn() {
    use std::os::unix::fs::PermissionsExt;
    let mut lab = Lab::new();
    let executable = lab.root.path().join("synthetic-fs-uae");
    std::fs::copy("/usr/bin/true", &executable).unwrap();
    std::fs::set_permissions(&executable, std::fs::Permissions::from_mode(0o700)).unwrap();
    lab.request.profile.executable = Some(executable.clone());
    let approval = lab.approve();
    let prepared = prepare_boot(&lab.request, &approval).unwrap();
    std::fs::remove_file(&executable).unwrap();
    std::fs::copy("/usr/bin/false", &executable).unwrap();
    let result = prepared.spawn();
    let refused = result.is_err();
    if let Ok((_, mut watched)) = result {
        let deadline = std::time::Instant::now() + Duration::from_secs(5);
        while watched.is_running() && std::time::Instant::now() < deadline {
            watched.poll();
            std::thread::sleep(Duration::from_millis(5));
        }
    }
    assert!(refused, "a replacement executable must never run");
}

