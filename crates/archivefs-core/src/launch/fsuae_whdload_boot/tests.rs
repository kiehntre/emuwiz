fn kick_slave(size: u32, checksum: u16) -> Vec<u8> {
    let mut code = vec![0; 96];
    code[..4].copy_from_slice(&[0x70, 0xff, 0x4e, 0x75]);
    code[4..12].copy_from_slice(b"WHDLOADS");
    code[12..14].copy_from_slice(&16u16.to_be_bytes());
    code[16..20].copy_from_slice(&(512u32 * 1024).to_be_bytes());
    code[24..26].copy_from_slice(&94u16.to_be_bytes());
    code[42..44].copy_from_slice(&52u16.to_be_bytes());
    code[44..48].copy_from_slice(&size.to_be_bytes());
    code[48..50].copy_from_slice(&checksum.to_be_bytes());
    code[52..67].copy_from_slice(b"kick34005.A500\0");
    let mut out = Vec::new();
    for word in [0x3f3u32, 0, 1, 0, 0, 24, 0x3e9, 24] {
        out.extend_from_slice(&word.to_be_bytes());
    }
    out.extend(code);
    out.extend(0x3f2u32.to_be_bytes());
    out
}

#[test]
fn kickemu_dependencies_check_rom_rtb_size_and_crc() {
    for variant in ["correct", "no-rtb", "wrong-size", "wrong-crc"] {
        let mut lab = Lab::new();
        let rom = vec![0u8; 256 * 1024]; // Synthetic bytes, never real firmware.
        let slave = kick_slave(
            if variant == "wrong-size" {
                1
            } else {
                rom.len() as u32
            },
            if variant == "wrong-crc" { 0x1234 } else { 0 },
        );
        lab.repackage(&[("Nested/Game.slave", &slave), ("Nested/data", b"synthetic")]);
        lab.request.slave.as_mut().unwrap().parsed = parse_whdload_slave(&slave).unwrap();
        lab.request.slave.as_mut().unwrap().sha256 = digest(&slave);
        lab.manifest.game_key = digest(&slave);
        lab.request.profile.verified_identity = digest(&slave);
        lab.request.identity = CanonicalIdentityStatus::Resolved(ResolvedIdentity {
            platform_id: "Amiga".into(),
            game_key: digest(&slave),
        });
        for (name, bytes) in [
            ("Boot/Devs/Kickstarts/kick34005.A500", rom.as_slice()),
            (
                "Boot/Devs/Kickstarts/kick34005.A500.RTB",
                b"synthetic relocation bytes".as_slice(),
            ),
        ] {
            if variant == "no-rtb" && name.ends_with(".RTB") {
                continue;
            }
            let path = lab.manifest.template_root.join(name);
            std::fs::create_dir_all(path.parent().unwrap()).unwrap();
            std::fs::write(path, bytes).unwrap();
            lab.manifest.files.push(TemplateFile {
                path: name.into(),
                sha256: digest(bytes),
            });
        }
        lab.save();
        let approval = lab.approve();
        let result = prepare_boot(&lab.request, &approval);
        assert_eq!(
            result.is_ok(),
            variant == "correct",
            "{variant}: {:?}",
            result.err()
        );
    }
}

