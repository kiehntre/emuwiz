fn slave_bytes() -> Vec<u8> {
    let mut code = vec![0; 32];
    code[..4].copy_from_slice(&[0x70, 0xff, 0x4e, 0x75]);
    code[4..12].copy_from_slice(b"WHDLOADS");
    code[12..14].copy_from_slice(&1u16.to_be_bytes());
    code[16..20].copy_from_slice(&(512u32 * 1024).to_be_bytes());
    code[24..26].copy_from_slice(&30u16.to_be_bytes());
    code[30..].copy_from_slice(&[0x4e, 0x75]);
    let mut out = Vec::new();
    for word in [0x3f3u32, 0, 1, 0, 0, 8, 0x3e9, 8] {
        out.extend_from_slice(&word.to_be_bytes());
    }
    out.extend(code);
    out.extend(0x3f2u32.to_be_bytes());
    out
}

fn lha(entries: &[(&str, &[u8])]) -> Vec<u8> {
    let mut out = Vec::new();
    for (name, payload) in entries {
        let mut header = vec![(name.len() + 23) as u8, 0];
        header.extend_from_slice(b"-lh0-");
        header.extend_from_slice(&(payload.len() as u32).to_le_bytes());
        header.extend_from_slice(&(payload.len() as u32).to_le_bytes());
        header.extend_from_slice(&0u32.to_le_bytes());
        header.extend_from_slice(&[0x20, 0, name.len() as u8]);
        header.extend_from_slice(name.as_bytes());
        let mut crc = crate::dat::archive::lha_header::Crc16::default();
        crc.update(payload);
        header.extend_from_slice(&crc.finish().to_le_bytes());
        header.push(0);
        header[1] = header[2..].iter().fold(0u8, |s, b| s.wrapping_add(*b));
        out.extend(header);
        out.extend_from_slice(payload);
    }
    out.push(0);
    out
}

struct Lab {
    root: tempfile::TempDir,
    request: WHDLoadLaunchInput,
    manifest: BootManifest,
}
impl Lab {
    fn new() -> Self {
        let root = tempfile::tempdir().unwrap();
        let path = root.path();
        // Host utilities may be symlinks on CI. Only fixture copies enter the
        // no-follow launch contract; production paths must remain link-free.
        std::fs::copy("/usr/bin/true", path.join("true")).unwrap();
        std::fs::copy("/usr/bin/dash", path.join("dash")).unwrap();
        let slave = slave_bytes();
        let package = lha(&[
            ("Nested/Game.slave", &slave),
            ("Nested/data", b"synthetic game data"),
        ]);
        std::fs::write(path.join("game.lha"), &package).unwrap();
        std::fs::write(
            path.join("fs-uae.conf"),
            b"amiga_model=A500\nhard_drive_9=/real/user/data\n",
        )
        .unwrap();
        let template = path.join("template");
        let mut files = Vec::new();
        for (name, bytes) in [
            (
                "Boot/C/WHDLoad",
                b"\x00\x00\x03\xf3$VER: WHDLoad 18.9 synthetic fixture".to_vec(),
            ),
            (
                "Boot/C/SetPatch",
                b"\x00\x00\x03\xf3synthetic SetPatch".to_vec(),
            ),
            (
                "Boot/C/uae-configuration",
                b"\x00\x00\x03\xf3synthetic exit tool".to_vec(),
            ),
            ("Firmware/boot.rom", vec![0; 512 * 1024]),
        ] {
            let file = template.join(name);
            std::fs::create_dir_all(file.parent().unwrap()).unwrap();
            std::fs::write(file, &bytes).unwrap();
            files.push(TemplateFile {
                path: name.into(),
                sha256: digest(&bytes),
            });
        }
        let manifest = BootManifest {
            schema: 1,
            machine: "A1200".into(),
            chip_memory_kib: 2048,
            fast_memory_kib: 8192,
            authorized_game: true,
            authorized_template: true,
            authorized_firmware: true,
            disposable_saves: true,
            provenance: "synthetic fixture generated by this test; no real game/firmware".into(),
            game_key: digest(&slave),
            package_sha256: digest(&package),
            slave_member: "Nested/Game.slave".into(),
            template_root: template,
            whdload_version: 18,
            files,
        };
        let request = WHDLoadLaunchInput {
            identity: CanonicalIdentityStatus::Resolved(ResolvedIdentity {
                platform_id: "Amiga".into(),
                game_key: digest(&slave),
            }),
            target: Some(VerifiedWHDLoadTarget {
                package_path: path.join("game.lha"),
                format: WhdloadPackageFormat::Lha,
            }),
            slave: Some(SelectedWHDLoadSlave {
                sha256: digest(&slave),
                artifact_path: path.join("game.lha"),
                name: "Game.slave".into(),
                parsed: parse_whdload_slave(&slave).unwrap(),
            }),
            profile: WHDLoadProfileInput {
                emulator: AmigaEmulatorKind::FsUae,
                profile_id: "test".into(),
                executable: Some(path.join("true")),
                configuration: Some(path.join("fs-uae.conf")),
                candidate_count: 1,
                eligible: true,
                kickstart: AmigaKickstartState::PresentUnverified,
                verified_identity: digest(&slave),
            },
            boot: Err("not inspected".into()),
        };
        let lab = Self {
            root,
            request,
            manifest,
        };
        lab.save();
        lab
    }
    fn save(&self) {
        std::fs::write(
            manifest_path(self.request.profile.configuration.as_ref().unwrap()),
            serde_json::to_vec(&self.manifest).unwrap(),
        )
        .unwrap();
    }
    fn approve(&mut self) -> BootApproval {
        let approval = inspect_boot(&self.request).unwrap();
        self.request.boot = Ok(approval.clone());
        approval
    }
    fn repackage(&mut self, entries: &[(&str, &[u8])]) {
        let bytes = lha(entries);
        std::fs::write(self.root.path().join("game.lha"), &bytes).unwrap();
        self.manifest.package_sha256 = digest(&bytes);
        self.save();
    }
}

