#[test]
fn staging_nested_game_is_disposable_and_does_not_inherit_live_mounts_or_trainers() {
    let mut lab = Lab::new();
    let approval = lab.approve();
    let prepared = prepare_boot(&lab.request, &approval).unwrap();
    let root = prepared.workspace_path();
    assert_eq!(
        std::fs::read(root.join("Game/Nested/data")).unwrap(),
        b"synthetic game data"
    );
    let config = std::fs::read_to_string(root.join("session.fs-uae")).unwrap();
    assert!(!config.contains("/real/user/data"));
    assert!(!config.contains(lab.root.path().to_str().unwrap()));
    let startup = std::fs::read_to_string(root.join("Boot/S/Startup-Sequence")).unwrap();
    assert!(startup.contains("Games:Nested"));
    assert!(!startup.contains("CUSTOM"));
    assert_eq!(
        prepared.command.arguments,
        vec![root.join("session.fs-uae").into_os_string()]
    );
    assert!(prepared.environment.iter().any(|(k, _)| k == "HOME"));
    assert!(
        !prepared
            .environment
            .iter()
            .any(|(k, _)| k.to_string_lossy().starts_with("FS_UAE"))
    );
    std::fs::write(root.join("Game/Nested/data"), b"session save").unwrap();
    assert_eq!(
        read(&approval.package.path, MAX_TOTAL).unwrap().1,
        approval.package
    );
    for dependency in &approval.dependencies {
        assert_eq!(read(&dependency.path, MAX_FILE).unwrap().1, *dependency);
    }
    let path = root.to_path_buf();
    drop(prepared);
    assert!(!path.exists());
}

